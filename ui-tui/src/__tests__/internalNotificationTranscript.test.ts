const sid = 'synthetic-notification-session'
// Synthetic public frames matching SessionAuthority._publish_pending/_stamp_claim; no live owner.
// Python's test_pending_notification_display separately exercises today's real producer and publisher.
const raw = '[IMPORTANT: Background process proc_synthetic_0 completed normally (exit code 0).\nCommand: printf SYNTHETIC_0\nOutput:\nSYNTHETIC_OUTPUT_0]\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]'

function sample(count: number, kind = 'process_complete') {
  const text = count === 1 ? raw : `${raw}\n${raw}`
  const display_text = count === 1 ? 'Background Process Finished: printf SYNTHETIC_0' : '2 Background Processes Finished'
  const card = { display_kind: kind, display_text, text }

  const pending = (status: string) => [{ admission_id: 'admission', authority_epoch: 1,
    display_kind: kind, display_text, execution_generation: status === 'started' ? 1 : null,
    input_id: 'input', outcome: null, ref: { profile_id: 'synthetic-profile', session_id: sid }, sequence: 1, status, text }]

  const info = (status: string) => ({ payload: { authority_epoch: 1, execution_generation: status === 'started' ? 1 : 0,
    pending: pending(status), running: status === 'started' }, session_id: sid, type: 'session.info' })

  const start = { admission_id: 'admission', authority_epoch: 1, execution_generation: 1, payload: card, session_id: sid, type: 'message.start' }
  const expected: Msg = { kind: 'event', role: 'system', text: display_text }
  const stored = { content: text, display_kind: kind, display_metadata: { display_text }, role: 'user' }

  return { card, expected, info, pending, start, stored, text }
}

function consumer(appended: Msg[]) {
  const handler = createGatewayEventHandler({
    composer: { dequeue: () => undefined, queueEditRef: { current: null }, sendQueued: vi.fn(), setInput: vi.fn() },
    gateway: { gw: { request: vi.fn(async () => null) }, rpc: vi.fn(async () => null) },
    session: { STARTUP_RESUME_ID: '', colsRef: { current: 80 }, newSession: vi.fn(), resetSession: vi.fn(), resumeById: vi.fn(), setCatalog: vi.fn() },
    submission: { submitRef: { current: vi.fn() } }, system: { bellOnComplete: false, sys: vi.fn() },
    transcript: { appendMessage: (message: Msg) => appended.push(message), panel: vi.fn(), setHistoryItems: vi.fn() },
    voice: { setProcessing: vi.fn(), setRecording: vi.fn(), setVoiceEnabled: vi.fn() }
  } as any)

  // Keep real publishWire + canonical adaptation + transcript consumer; replace socket construction only.
  const client = Object.create(GatewayClient.prototype) as any
  client.isCanonical = true
  client.publish = handler

  return (frame: unknown) => client.publishWire(structuredClone(frame))
}

function resume(data: ReturnType<typeof sample>, status?: string) {
  const messages = status === 'queued' ? [] : [data.stored]

  const snapshot = canonicalResult('session.resume', { authority_epoch: 1, execution_generation: status === 'queued' ? 0 : 1,
    display_messages: messages.map(row => ({ ...row, text: row.content })), info: {}, messages,
    pending: status ? data.pending(status) : [], running: status === 'started', session_id: sid, stored_session_id: sid })

  patchUiState({ info: snapshot.info })

  return toTranscriptMessages(snapshot.messages)
}

beforeEach(() => {
  vi.useFakeTimers()
  resetOverlayState(); resetUiState(); resetTurnState(); resetBubbleLedger(); turnController.fullReset()
  patchUiState({ info: { execution_epoch: '1', execution_generation: 0 }, sid })
})
afterEach(() => { turnController.fullReset(); vi.clearAllTimers(); vi.useRealTimers() })

for (const count of [1, 2]) {
  for (const active of [false, true]) {
    it(`${count} completion(s): ${active ? 'active' : 'foreground final then idle'} -> queued -> started -> replay`, () => {
      const data = sample(count)
      const appended: Msg[] = []
      const send = consumer(appended)
      send({ authority_epoch: 1, execution_generation: 0, payload: {}, session_id: sid, type: 'message.start' })

      if (!active) {
        send({ authority_epoch: 1, execution_generation: 0, payload: { text: 'Foreground done' }, session_id: sid, type: 'message.complete' })
        expect(getUiState().busy).toBe(false)
        expect(appended.some(row => row.role === 'assistant' && row.text === 'Foreground done')).toBe(true)
      }

      const before = appended.length
      const queued = data.info('queued')
      queued.payload.running = active
      send(queued)

      if (active) {
        expect(getUiState().busy).toBe(true)
        expect(appended).toHaveLength(before)
        send({ authority_epoch: 1, execution_generation: 0, payload: { text: 'Active turn done' }, session_id: sid, type: 'message.complete' })
      }

      const afterForeground = appended.length
      send(data.start); send(data.info('started'))
      send(data.start); send(data.info('started'))
      expect(appended.slice(afterForeground), 'completion must be one concise timeline event, never a human envelope').toEqual([data.expected])
      expect(data.start.payload.text).toBe(data.text)
    })
  }

  it(`${count} completion(s): start-only late attachment deduplicates replay`, () => {
    const data = sample(count)
    const appended: Msg[] = []
    const send = consumer(appended)
    send(data.start); send(data.start); send(data.info('started'))
    expect(appended, 'start card must render without observing the queued transition').toEqual([data.expected])
  })
  it(`${count} completion(s): queued resume renders on claim`, () => {
    const data = sample(count)
    const appended = resume(data, 'queued')
    const send = consumer(appended)
    // Reconnect can observe the started pending snapshot without its message.start frame.
    send(data.info('started')); send(data.start)
    expect(appended, 'pending presentation must survive resume and a missing start frame').toEqual([data.expected])
  })
  it(`${count} completion(s): started resume already contains the notice`, () => {
    const data = sample(count)
    const appended = resume(data, 'started')
    const send = consumer(appended)
    send(data.start); send(data.info('started'))
    expect(appended).toEqual([data.expected])
  })
  it(`${count} completion(s): settled reconnect retains model rows separately`, () => {
    const data = sample(count)
    expect(resume(data)).toEqual([data.expected])
    expect(data.stored.content).toBe(data.text)
  })
}

it('human identical notification text stays visible through live and resumed consumers', () => {
  const data = sample(1)
  const appended: Msg[] = []
  const send = consumer(appended)

  const humanInfo = (status: string) => {
    const frame = data.info(status)
    frame.payload.pending = frame.payload.pending.map(row => ({ ...row, display_kind: undefined, display_text: undefined })) as any

    return frame
  }

  send(humanInfo('queued')); send({ ...data.start, payload: {} }); send(humanInfo('started'))
  expect(appended).toEqual([{ role: 'user', text: data.text }])
  const snapshot = canonicalResult('session.resume', { authority_epoch: 1, execution_generation: 1, info: {}, messages: [{ content: data.text, role: 'user' }], pending: [] })
  expect(toTranscriptMessages(snapshot.messages)).toEqual(appended)
})

it('async delegation completions use the same existing concise timeline presentation', () => {
  const data = sample(1, 'async_delegation_complete')
  const appended: Msg[] = []
  const send = consumer(appended)
  send(data.info('queued')); send(data.start); send(data.info('started'))
  expect(appended).toEqual([data.expected])
})

it('a typed completion without a title retains the existing generic timeline notice', () => {
  const data = sample(1)
  const appended: Msg[] = []
  consumer(appended)({ ...data.start, payload: { display_kind: 'process_complete', text: data.text } })
  expect(appended).toEqual(toTranscriptMessages([{ role: 'user', text: data.text, display_kind: 'process_complete' }]))
  expect(appended).toHaveLength(1)
})
