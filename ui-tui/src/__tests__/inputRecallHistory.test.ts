import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

import type * as React from 'react'
import { afterEach, expect, it, vi } from 'vitest'

// Exercise the real hook/file seam without mounting the terminal renderer.
vi.mock('react', async importOriginal => ({
  ...(await importOriginal<typeof React>()),
  useRef: <T,>(current: T) => ({ current }),
  useState: <T,>(initial: T) => [initial, vi.fn()]
}))

const footer = '[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]'
const notification = `[IMPORTANT: Background process proc_synthetic completed normally (exit code 0).\nCommand: synthetic-check\nOutput: synthetic result]\n\n${footer}`
const encode = (text: string) => `\n# synthetic timestamp\n${text.split('\n').map(line => `+${line}`).join('\n')}\n`

async function fixture(entries: string[]) {
  const home = mkdtempSync(resolve('../tmp/input-history-repair/recall-'))
  vi.stubEnv('HERMES_HOME', home)
  vi.resetModules()
  const file = join(home, '.hermes_history')
  const original = entries.map(encode).join('')
  writeFileSync(file, original)

  return { file, original, history: await import('../lib/history.js'), hook: await import('../hooks/useInputHistory.js') }
}

afterEach(() => vi.unstubAllEnvs())

it('does not expose a legacy machine completion to the real composer history hook or rewrite disk', async () => {
  const human = ['hello', '/status', 'first line\n\nsecond line', `Please explain this notification:\n${notification}`, 'IMPORTANT: notification troubleshooting', `Quoted footer: ${footer}`, 'assistant: synthetic answer', 'tool: synthetic output']
  const { file, original, hook } = await fixture([...human, notification])
  const consumer = hook.useInputHistory()
  expect(consumer.historyRef.current).toEqual(human)
  expect(consumer.historyRef.current.at(-1)).toBe('tool: synthetic output')
  expect(readFileSync(file, 'utf8')).toBe(original)
})

it('keeps explicitly submitted human text, even a verbatim notification example, after reload', async () => {
  const { file, history, hook } = await fixture([notification, 'older human input'])
  const consumer = hook.useInputHistory()
  consumer.pushHistory(notification)
  consumer.pushHistory('/status\nwith multiline arguments')
  expect(consumer.historyRef.current).toEqual(['older human input', notification, '/status\nwith multiline arguments'])
  const saved = readFileSync(file, 'utf8')
  vi.resetModules()
  const reloaded = await import('../lib/history.js')
  expect(reloaded.load()).toEqual(history.load())
  expect(readFileSync(file, 'utf8')).toBe(saved)
})

it('does not mistake a partial marker, quoted example or different IMPORTANT message for machinery', async () => {
  const human = [notification.replace(footer, ''), `${notification}\nMy question follows.`, `> ${notification}`, `[IMPORTANT: Human request]\n\n${footer}`]
  const { history } = await fixture(human)
  expect(history.load()).toEqual(human)
  history.append('  human draft\nsecond line  ')
  history.append('human draft\nsecond line')
  expect(history.load()).toEqual([...human, 'human draft\nsecond line'])
})
