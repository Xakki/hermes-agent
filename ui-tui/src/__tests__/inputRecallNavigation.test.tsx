import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { PassThrough } from 'node:stream'

import type * as Ink from '@hermes/ink'
import React from 'react'
import { expect, it, vi } from 'vitest'

import type { InputHandlerContext, UseComposerStateResult } from '../app/interfaces.js'
import type { GatewayClient } from '../gatewayClient.js'
import type { SessionInfo } from '../types.js'

type InputHandler = Parameters<typeof Ink.useInput>[0]

const inputHarness = vi.hoisted(() => ({ handler: undefined as InputHandler | undefined }))

// Same renderSync adapter as subscriptionOverlay.test.tsx: intercept registration
// only; React state, composer/history hooks, stores and the key callback stay real.
vi.mock('@hermes/ink', async importOriginal => ({
  ...(await importOriginal<typeof Ink>()),
  useInput: (handler: InputHandler) => { inputHarness.handler = handler }
}))

it('navigates only human recall entries with the registered Up/Down callback and restores the draft', async () => {
  mkdirSync(resolve('../tmp/project-input-history'), { recursive: true, mode: 0o700 })
  const home = mkdtempSync(resolve('../tmp/project-input-history/navigation-human-'))
  const projectKey = 'a'.repeat(64)
  mkdirSync(resolve(home, 'input-history'))
  const file = resolve(home, 'input-history', projectKey)
  const footer = '[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]'
  const notification = `[IMPORTANT: Background process proc_synthetic completed normally (exit code 0).\nCommand: synthetic-check\nOutput: synthetic result]\n\n${footer}`
  const multiline = 'human first line\n\nhuman final line'
  const humans = ['older human input', multiline, '/status']

  const original = [...humans, notification].map(text =>
    `\n# synthetic timestamp\n${text.split('\n').map(line => `+${line}`).join('\n')}\n`
  ).join('')

  writeFileSync(file, original)
  vi.stubEnv('HERMES_HOME', home)

  const { renderSync } = await import('@hermes/ink')
  const { useComposerState } = await import('../app/useComposerState.js')
  const { useInputHandlers } = await import('../app/useInputHandlers.js')
  const { setInputSelection } = await import('../app/inputSelectionStore.js')
  const { resetOverlayState } = await import('../app/overlayStore.js')
  const { patchUiState, resetUiState } = await import('../app/uiStore.js')
  resetOverlayState()
  resetUiState()
  patchUiState({ info: { input_history_key: projectKey } as SessionInfo })

  const gw = { isCanonical: true, request: vi.fn(async () => ({})) } as unknown as GatewayClient
  const submitRef = { current: vi.fn() }
  const stdout = Object.assign(new PassThrough(), { columns: 100, rows: 30, isTTY: false })
  let composer: UseComposerStateResult

  function Harness() {
    composer = useComposerState({ gw, submitRef, sys: vi.fn() })
    useInputHandlers({
      composer,
      actions: { sys: vi.fn() },
      gateway: { gw },
      terminal: { stdout, hasSelection: false },
      voice: { enabled: false },
      wheelStep: 1
    } as InputHandlerContext)

    return null
  }

  const instance = renderSync(<Harness />, {
    stdin: Object.assign(new PassThrough(), { isTTY: false }) as NodeJS.ReadStream,
    stdout: stdout as NodeJS.WriteStream,
    stderr: new PassThrough() as NodeJS.WriteStream,
    patchConsole: false
  })

  const expectInput = async (text: string) => {
    await vi.waitFor(() => {
      instance.rerender(<Harness />)
      expect(composer.state.input).toBe(text)
    })
  }

  const press = async (direction: 'up' | 'down', expected: string) => {
    // A caret on the first line exercises Up's actual line-boundary gate, even
    // when the recalled text spans lines. No navigation logic is duplicated.
    setInputSelection({
      start: 0, end: 0, value: composer.state.input,
      clear: vi.fn(), collapseToEnd: vi.fn(), copy: vi.fn(), cut: vi.fn()
    })
    expect(inputHarness.handler).toBeTypeOf('function')
    inputHarness.handler!('', { upArrow: direction === 'up', downArrow: direction === 'down' } as Parameters<InputHandler>[1], {} as Parameters<InputHandler>[2])
    await expectInput(expected)
  }

  try {
    expect(composer!.refs.historyRef.current).toEqual(humans)
    composer!.actions.setInput('unsent human draft\nsecond draft line')
    await expectInput('unsent human draft\nsecond draft line')
    await press('up', '/status')
    await press('up', multiline)
    await press('up', 'older human input')
    await press('up', 'older human input')
    await press('down', multiline)
    await press('down', '/status')
    await press('down', 'unsent human draft\nsecond draft line')
    expect(composer!.state.historyIdx).toBeNull()
    expect(readFileSync(file, 'utf8')).toBe(original)

    // A real composer append is human provenance, including a verbatim example.
    composer!.actions.pushHistory(notification)
    await press('up', notification)
    await press('up', '/status')
    await press('down', notification)
    await press('down', 'unsent human draft\nsecond draft line')
    expect(composer!.state.historyIdx).toBeNull()
  } finally {
    instance.unmount()
    instance.cleanup()
    setInputSelection(null)
    resetOverlayState()
    resetUiState()
    vi.unstubAllEnvs()
    inputHarness.handler = undefined
  }
})
